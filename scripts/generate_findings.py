"""Write docs/FINDINGS.md with every number computed from the SQLite database.

    python scripts/generate_findings.py

Nothing in the findings is typed by hand, so re-running after a data refresh regenerates all of it.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd  # noqa: E402

from nhs_ed.config import DB_PATH, PROJECT_ROOT, SQL_DIR  # noqa: E402
from nhs_ed.db import connect  # noqa: E402


def run(con, name):
    return pd.read_sql_query((SQL_DIR / "queries" / name).read_text(), con)


HEADERS = {
    "month_label": "Month",
    "attendances_per_day": "Attendances per day",
    "pct_within_4h": "Within 4 hours, %",
    "change_vs_prev_month_pts": "Change on previous month, points",
    "region": "Region",
    "type1_share_of_attendances_pct": "Type 1 share of attendances, %",
    "type1_pct_within_4h": "Type 1 within 4 hours, %",
    "pooled_all_types_pct_within_4h": "All types pooled within 4 hours, %",
    "pooled_minus_type1_pts": "Pooled minus Type 1, points",
    "rank_best_first": "Rank, best first",
    "attendances": "Attendances",
    "org_name": "Organisation",
    "type1_attendances": "Type 1 attendances",
    "over_12h_dta_waits": "Over 12 hour waits",
    "group_label": "Group",
    "org_code": "Code",
    "admissions_per_100_attendances": "Admissions per 100 attendances",
}


def md(df: pd.DataFrame) -> str:
    cols = [HEADERS.get(c, c.replace("_", " ")) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("not available" if pd.isna(v) else (f"{v:,}" if isinstance(v, int) else str(v)) for v in r) + " |")
    return "\n".join(lines)


def main() -> None:
    con = connect(DB_PATH)
    q1 = run(con, "01_national_monthly_by_type.sql")
    t1 = q1[q1.ae_type == "Type 1"].reset_index(drop=True)
    mom = run(con, "04_national_type1_month_on_month.sql")
    regions = run(con, "02_regional_type1_performance.sql")
    trusts = run(con, "03_trust_ranking_type1.sql")
    mix = run(con, "08_type_mix_vs_pooled_performance.sql")
    adm = run(con, "10_trust_type1_admission_ratio_extremes.sql")
    dta = run(con, "07_trust_12h_dta_waits.sql")

    yr = con.execute("""SELECT SUM(attendances + booked_attendances),
                               100.0*(1-1.0*SUM(over_4hrs + booked_over_4hrs)/SUM(attendances + booked_attendances)),
                               100.0*(1-1.0*SUM(over_4hrs)/SUM(attendances))
                        FROM v_ae_type_month WHERE ae_type='Type 1'""").fetchone()
    shares = pd.read_sql_query("SELECT ae_type, SUM(attendances + booked_attendances) a FROM fact_ae_type_month GROUP BY ae_type", con).set_index("ae_type").a
    dta_tot = con.execute("SELECT SUM(dta_12h_plus) FROM fact_org_month").fetchone()[0]
    dta_m = pd.read_sql_query("SELECT m.month_label, SUM(dta_12h_plus) n FROM fact_org_month f JOIN dim_month m USING(month_start) GROUP BY f.month_start ORDER BY f.month_start", con)
    hi, lo = mom.loc[mom.pct_within_4h.idxmax()], mom.loc[mom.pct_within_4h.idxmin()]
    top, bottom = trusts.head(5), trusts.tail(5)
    peak = dta_m.loc[dta_m.n.idxmax()]
    ratios = pd.read_sql_query("""SELECT 100.0*SUM(emergency_admissions)/SUM(attendances + booked_attendances) AS r FROM v_ae_type_month
                                  WHERE ae_type='Type 1' AND is_children_or_womens=0 GROUP BY org_code HAVING SUM(attendances + booked_attendances)>0""", con).r

    text = f"""# Findings

This file is generated by `scripts/generate_findings.py` from `data/processed/ae_2025_26.sqlite`. Every number is computed from the 12 monthly files, April 2025 to March 2026. The findings describe the reported data and do not explain it, because the project has no information on case mix, staffing, bed capacity or local recording practice. Performance means the percentage of Type 1 attendances admitted, transferred or discharged within 4 hours. Booked appointments are included, as in NHS England's published headline, and the percentage is calculated from summed counts. See [OFFICIAL_RECONCILIATION.md](OFFICIAL_RECONCILIATION.md).

## 1. National Type 1 performance over the year

Type 1 departments recorded {yr[0]:,} attendances, with booked appointments included, in the 12 months. {yr[1]:.1f}% of them were seen within 4 hours, or {yr[2]:.1f}% on an unbooked-only basis. The choice changes the headline by {abs(yr[2]-yr[1]):.1f} points.

Monthly Type 1 performance ranged from {lo.pct_within_4h:.1f}% in {lo.month_label} to {hi.pct_within_4h:.1f}% in {hi.month_label}. The largest month-on-month change was {mom.change_vs_prev_month_pts.abs().max():.1f} points, in {mom.loc[mom.change_vs_prev_month_pts.abs().idxmax()].month_label}.

{md(mom)}

## 2. Department types behave differently

Type 1 accounts for {shares['Type 1'] / shares.sum() * 100:.0f}% of attendances. Over the full year, with booked appointments included, there were {shares['Type 1']:,} Type 1 attendances, {shares['Other']:,} at Other A&E departments and {shares['Type 2']:,} at Type 2 departments.

Monthly four-hour performance ranged from {t1.pct_within_4h.min():.1f}% to {t1.pct_within_4h.max():.1f}% for Type 1, from {q1[q1.ae_type=='Other'].pct_within_4h.min():.1f}% to {q1[q1.ae_type=='Other'].pct_within_4h.max():.1f}% for Other A&E departments, and from {q1[q1.ae_type=='Type 2'].pct_within_4h.min():.1f}% to {q1[q1.ae_type=='Type 2'].pct_within_4h.max():.1f}% for Type 2.

Pooling the types would add {mix.pooled_minus_type1_pts.min():.1f} to {mix.pooled_minus_type1_pts.max():.1f} points to each region's figure, as shown by query 08. For this reason the project compares Type 1 only.

{md(mix)}

## 3. Regions, Type 1 only, full year

{md(regions)}

## 4. Trusts, Type 1 only

This ranking has {len(trusts)} trusts and excludes children's and women's providers. The best trust is at {trusts.pct_within_4h.max():.1f}% and the lowest at {trusts.pct_within_4h.min():.1f}%, with a median of {trusts.pct_within_4h.median():.1f}%.

Highest 5:

{md(top[['rank_best_first','org_name','region','type1_attendances','pct_within_4h']])}

Lowest 5:

{md(bottom[['rank_best_first','org_name','region','type1_attendances','pct_within_4h']])}

A league table describes reported performance. It does not adjust for case mix, size or recording practice, and differences of a few points between neighbouring trusts should not be over-interpreted.

## 5. Over 12 hour waits from decision to admit

Across all organisations, {dta_tot:,} patients waited over 12 hours from decision to admit in the year. The peak month was {peak.month_label}, with {int(peak.n):,}. The source does not split these counts by A&E type. The five trusts with the most waits are below. These are counts and not rates, and larger trusts naturally have more.

{md(dta[['org_name','region','over_12h_dta_waits']].head(5))}

## 6. Admission ratios

Type 1 emergency admissions per 100 attendances range from {adm.admissions_per_100_attendances.min():.1f} to {adm.admissions_per_100_attendances.max():.1f} across trusts, with a median of {ratios.median():.1f}. A spread this wide may partly reflect how admissions are recorded or how same-day emergency care is organised, and not differences in care. The spread is flagged and not explained, and the ratio should not be used as a quality score.

{md(adm)}
"""
    out = PROJECT_ROOT / "docs" / "FINDINGS.md"
    out.write_text(text)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
